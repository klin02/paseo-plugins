import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../server/', import.meta.url);
const python = await readFile(new URL('desktop_transfer.py', root), 'utf8');
const powershell = await readFile(new URL('start-desktop-transfer.ps1', root), 'utf8');
await writeFile(new URL('assets.ts', root), '// Generated by npm run assets from the two reviewed helper scripts.\n' +
  'export const pythonSource = ' + JSON.stringify(python) + ';\n' +
  'export const powershellSource = ' + JSON.stringify(powershell) + ';\n');
